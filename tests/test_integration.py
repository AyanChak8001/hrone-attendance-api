    def test_concurrent_regularizations_preserve_successful_audit_entries(self):
        code = "EMP9402"
        date = "2026-08-04"
        self._insert_employee_and_logs(
            _employee(code, "Concurrent Regularization", "Concurrency"),
            [_attendance(code, date, "PRESENT", datetime(2026, 8, 4, 4), datetime(2026, 8, 4, 13))],
        )
        bodies = [
            {"status": "ABSENT", "reason": "Concurrent correction A", "regularized_by": "hr-a"},
            {"status": "LEAVE", "reason": "Concurrent correction B", "regularized_by": "hr-b"},
        ]
        with ThreadPoolExecutor(max_workers=2) as executor:
            responses = list(executor.map(lambda body: self.http.patch(f"/attendance/{code}/{date}", json=body), bodies))
        statuses = [response.status_code for response in responses]
        self.assertTrue(all(status in (200, 409) for status in statuses))
        self.assertGreaterEqual(statuses.count(200), 1)
        self.assertEqual(statuses.count(409) + statuses.count(200), 2)
        stored = main.db.attendance_logs.find_one({"emp_code": code, "date": date})
        self.assertEqual(len(stored["history"]), statuses.count(200))

