def _assert_safe_database_name(name: str) -> None:
    if name == "attendance_db" or not TEST_DB_PATTERN.fullmatch(name) or name != TEST_DB:
        raise AssertionError(f"refusing database outside this test run: {name!r}")


def cleanup_test_database() -> None:
    """Explicitly remove only this run's database when the caller opts in."""
    if os.environ.get("HROne_CLEANUP_TEST_DB") != "1":
        raise RuntimeError("set HROne_CLEANUP_TEST_DB=1 to opt into cleanup")
    _assert_safe_database_name(TEST_DB)
    client = MongoClient(TEST_URI)
    try:
        client.drop_database(TEST_DB)
    finally:
        client.close()


class IntegrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        _assert_safe_database_name(TEST_DB)
        if os.environ.get("MONGO_URI") != TEST_URI or os.environ.get("MONGO_DB") != TEST_DB:
            raise AssertionError("integration environment was redirected")
        if main.db.name != TEST_DB:
            raise AssertionError(f"application selected unexpected database: {main.db.name!r}")

        info = main.db.command("buildInfo")
        if not str(info.get("version", "")).startswith("7."):
            raise AssertionError(f"expected Docker MongoDB 7.x, got {info.get('version')!r}")

        cls.http = TestClient(main.app)
        cls.http.__enter__()
        main.db.employees.insert_many(EMPLOYEES)
        main.db.attendance_logs.insert_many(ANALYTIC_LOGS)

        # Records used by the mutating endpoint tests are separate from the
        # analytics fixtures, so test order cannot alter analytic expectations.
        main.db.attendance_logs.insert_many(
            [
                _attendance("EMP0002", "2026-07-11", "PRESENT", datetime(2026, 7, 11, 4), None),
                _attendance("EMP0003", "2026-07-12", "PRESENT", datetime(2026, 7, 12, 4), datetime(2026, 7, 12, 13)),
            ]
        )

    @classmethod
    def tearDownClass(cls) -> None:
        cls.http.__exit__(None, None, None)
        main.client.close()

