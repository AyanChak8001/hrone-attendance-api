def _attendance(
    emp_code: str,
    date: str,
    status: str,
    punch_in: datetime | None,
    punch_out: datetime | None,
    late_minutes: int = 0,
) -> dict:
    work_hours = None
    if punch_in is not None and punch_out is not None:
        work_hours = round((punch_out - punch_in).total_seconds() / 3600, 2)
    return {
        "emp_code": emp_code,
        "date": date,
        "status": status,
        "punch_in": punch_in,
        "punch_out": punch_out,
        "work_hours": work_hours,
        "late_minutes": late_minutes,
        "overtime_minutes": 0,
        "half_day": bool(work_hours is not None and work_hours < 4.5),
        "history": [],
    }


def _employee(code: str, name: str, department: str, joined_on: str = "2026-08-01") -> dict:
    return {
        "emp_code": code,
        "name": name,
        "email": f"{code.lower()}@integration.example.com",
        "department": department,
        "shift_start": "09:30",
        "shift_end": "18:30",
        "joined_on": joined_on,
        "created_at": datetime(2026, 1, 1),
    }


def _epoch_ms(value: datetime) -> int:
    return int(value.replace(tzinfo=timezone.utc).timestamp() * 1000)


def _parallel(count: int, function):
    with ThreadPoolExecutor(max_workers=count) as executor:
        return list(executor.map(lambda _: function(), range(count)))


def _contains_execution_stats(value) -> bool:
    if isinstance(value, dict):
        return "executionStats" in value or any(_contains_execution_stats(item) for item in value.values())
    if isinstance(value, list):
        return any(_contains_execution_stats(item) for item in value)
    return False


