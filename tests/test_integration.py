    def test_admin_explain_supports_all_targets_and_preserves_filters(self):
        cases = [
            (
                "attendance_list",
                {"emp_code": "EMP0001", "date_from": "2026-07-06", "date_to": "2026-07-08", "status": "PRESENT", "page": 2, "page_size": 5},
                "attendance_logs",
            ),
            ("employee_monthly", {"emp_code": "EMP0001", "month": "2026-07"}, "attendance_logs"),
            ("department_summary", {"month": "2026-07", "department": "Engineering"}, "employees"),
            ("late_leaderboard", {"month": "2026-07", "department": "Engineering", "limit": 2}, "attendance_logs"),
            ("department_trend", {"department": "Engineering", "from": "2026-07-06", "to": "2026-07-08"}, "employees"),
        ]
        for endpoint, params, collection in cases:
            with self.subTest(endpoint=endpoint):
                response = self.http.get(f"/admin/explain/{endpoint}", params=params)
                self.assertEqual(response.status_code, 200)
                payload = response.json()
                self.assertEqual(payload["endpoint"], endpoint)
                self.assertEqual(payload["collection"], collection)
                explain = payload["explain"]
                self.assertTrue(_contains_execution_stats(explain))
                command = explain["command"]
                if endpoint == "attendance_list":
                    self.assertEqual(command["find"], collection)
                    self.assertEqual(command["filter"]["emp_code"], "EMP0001")
                    self.assertEqual(command["filter"]["status"], "PRESENT")
                    self.assertEqual(command["skip"], 5)
                    self.assertEqual(command["limit"], 5)
                else:
                    self.assertEqual(command["aggregate"], collection)
                    pipeline_text = str(command["pipeline"])
                    self.assertIn("2026", pipeline_text)
                    if endpoint == "employee_monthly":
                        self.assertIn("EMP0001", pipeline_text)
                    if endpoint == "department_trend":
                        self.assertIn("Engineering", pipeline_text)
                    if endpoint == "department_summary":
                        self.assertIn("Engineering", pipeline_text)
                    if endpoint == "late_leaderboard":
                        self.assertIn("Engineering", pipeline_text)
                        self.assertIn("2", pipeline_text)

