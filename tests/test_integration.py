        self.assertEqual(response.status_code, 200)
        record = response.json()
        self.assertEqual(record["punch_in"], corrected_in)
        self.assertEqual(record["punch_out"], _epoch_ms(original_out))
        self.assertEqual(len(record["history"]), 1)
        self.assertEqual(record["history"][0]["by"], "hr-complete")
        self.assertIn("punch_in", record["history"][0]["changes"])

